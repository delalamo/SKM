#!/usr/bin/env python3
"""Refresh the list of author surnames that are also ordinary English words.

The claim-summary rule flags any bibliography surname, but a surname such as
Long, Park or Rose is flagged only in author contexts ("Park et al.",
"Park (2020)", "Park and Lee", "Park's"). Re-run after the bibliography grows:

  python3 _tools/refresh_author_lists.py

Needs pyspellchecker (``pip install -r _tools/requirements.txt``).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from vaultlib import bib as biblib  # noqa: E402
from vaultlib import paths  # noqa: E402

HEADER = (
  "# Author surnames that are also ordinary English words. Generated by\n"
  "# _tools/refresh_author_lists.py; flagged in claim summaries only in author\n"
  "# contexts (\"Park et al.\", \"Park (2020)\", \"Park and Lee\", \"Park's\").\n"
)


def main(argv: list[str] | None = None) -> int:
  parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
  parser.add_argument("--bib", type=Path, default=paths.DEFAULT_BIB)
  parser.add_argument("--data", type=Path, default=paths.DEFAULT_DATA)
  parser.add_argument("--min-frequency", type=int, default=50, help="minimum corpus frequency for a common word")
  args = parser.parse_args(argv)
  from spellchecker import SpellChecker

  frequency = SpellChecker(language="en").word_frequency
  surnames = biblib.surnames(biblib.load(args.bib))
  common = sorted({name.lower() for name in surnames if frequency[name.lower()] >= args.min_frequency})
  out = args.data / "ambiguous_surnames.txt"
  out.write_text(HEADER + "".join(f"{word}\n" for word in common), encoding="utf-8")
  print(f"wrote {len(common)} ambiguous surnames (of {len(surnames)}) to {out}")
  return 0


if __name__ == "__main__":
  sys.exit(main())
